import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const appColorPath = resolve(__dirname, '../src/presentation/design-system/AppColor.ts');
const outputPath = resolve(__dirname, '../src/presentation/design-system/colors.css');

const source = readFileSync(appColorPath, 'utf8');
const transpiled = ts.transpileModule(source, {
  compilerOptions: {
    module: ts.ModuleKind.CommonJS,
    target: ts.ScriptTarget.ES2020,
  },
}).outputText;

const moduleShim = { exports: {} };
const exportsShim = moduleShim.exports;
const run = new Function('module', 'exports', transpiled);
run(moduleShim, exportsShim);

const { appColor, appSemanticColor } = moduleShim.exports;

if (!appColor || !appSemanticColor) {
  throw new Error('Unable to load appColor or appSemanticColor from AppColor.ts');
}

const createScaleVariables = () =>
  Object.entries(appColor)
    .flatMap(([family, tones]) =>
      Object.entries(tones).map(([tone, value]) => `  --${family}-${tone}: ${value};`),
    )
    .join('\n');

const createSemanticVariables = (theme) => {
  const semantic = appSemanticColor[theme];

  return [
    `  --surface-primary: ${semantic.surfacePrimary};`,
    `  --surface-secondary: ${semantic.surfaceSecondary};`,
    `  --text-primary: ${semantic.textPrimary};`,
    `  --text-secondary: ${semantic.textSecondary};`,
    `  --text-tertiary: ${semantic.textTertiary};`,
    `  --text-border: ${semantic.textBorder};`,
    `  --text-disabled: ${semantic.textDisabled};`,
    `  --primary-main: ${semantic.primaryMain};`,
    `  --primary-light: ${semantic.primaryLight};`,
  ].join('\n');
};

const createDerivedVariables = (theme) => {
  if (theme === 'dark') {
    return [
      '  --bg-0: var(--pink-900);',
      '  --bg-1: color-mix(in srgb, var(--pink-900) 70%, var(--neutral-black));',
      '  --ink: var(--text-primary);',
      '  --muted: var(--text-tertiary);',
      '  --line: var(--text-border);',
      '  --panel: color-mix(in srgb, var(--surface-primary) 85%, var(--pink-900));',
      '  --panel-soft: color-mix(in srgb, var(--surface-secondary) 82%, var(--pink-800));',
      '  --accent: var(--primary-main);',
      '  --accent-2: var(--pink-400);',
      '  --danger: var(--red-400);',
      '  --focus: var(--yellow-400);',
    ].join('\n');
  }

  return [
    '  --bg-0: color-mix(in srgb, var(--pink-100) 55%, var(--neutral-white));',
    '  --bg-1: color-mix(in srgb, var(--pink-200) 35%, var(--neutral-white));',
    '  --ink: var(--text-primary);',
    '  --muted: var(--text-tertiary);',
    '  --line: var(--text-border);',
    '  --panel: color-mix(in srgb, var(--surface-primary) 92%, var(--pink-100));',
    '  --panel-soft: color-mix(in srgb, var(--surface-secondary) 84%, var(--pink-100));',
    '  --accent: var(--primary-main);',
    '  --accent-2: var(--pink-500);',
    '  --danger: var(--red-500);',
    '  --focus: var(--yellow-500);',
  ].join('\n');
};

const css = `/* AUTO-GENERATED by scripts/generate-design-system-css.mjs. Do not edit manually. */
:root {
${createScaleVariables()}
${createSemanticVariables('dark')}
${createDerivedVariables('dark')}
}

.light {
${createSemanticVariables('light')}
${createDerivedVariables('light')}
}
`;

writeFileSync(outputPath, css, 'utf8');
console.log(`Generated ${outputPath}`);
